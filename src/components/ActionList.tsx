"use client";

import { useMemo, useState } from "react";
import type { ApiData } from "@/lib/types";
import { buildActions, ActionStatus, Priority } from "@/lib/actions";

const STATUSES: ActionStatus[] = ["Open", "In progress", "Done"];

const PRIORITY_STYLE: Record<Priority, string> = {
  High: "bg-red-100 text-red-800",
  Medium: "bg-amber-100 text-amber-800",
  Low: "bg-slate-100 text-slate-700",
};

export default function ActionList({ data }: { data: ApiData }) {
  const actions = useMemo(() => buildActions(data), [data]);
  // status changes are kept in memory only (see limitations in README)
  const [status, setStatus] = useState<Record<string, ActionStatus>>({});

  return (
    <section className="space-y-3">
      <div>
        <h2 className="text-lg font-semibold">Recommended actions</h2>
        <p className="text-xs text-slate-500">
          Generated by rules from the gaps above. Status changes are not saved.
        </p>
      </div>

      {actions.length === 0 ? (
        <p className="rounded-xl border border-slate-200 bg-white p-4 text-sm text-slate-500">
          Nothing needs action in this view. All indicators are On Track.
        </p>
      ) : (
        <div className="overflow-x-auto rounded-xl border border-slate-200 bg-white shadow-sm">
          <table className="w-full text-sm">
            <thead className="text-left text-xs text-slate-500">
              <tr>
                <th className="px-4 py-2 font-medium">Action</th>
                <th className="px-2 py-2 font-medium">Owner</th>
                <th className="px-2 py-2 font-medium">Priority</th>
                <th className="px-2 py-2 font-medium">Due</th>
                <th className="px-2 py-2 font-medium">Linked metric</th>
                <th className="px-4 py-2 font-medium">Status</th>
              </tr>
            </thead>
            <tbody>
              {actions.map((a) => {
                const current = status[a.title] ?? a.status;
                return (
                  <tr key={a.title} className="border-t border-slate-100 align-top">
                    <td
                      className={`px-4 py-3 font-medium ${
                        current === "Done" ? "text-slate-400 line-through" : ""
                      }`}
                    >
                      {a.title}
                    </td>
                    <td className="whitespace-nowrap px-2 py-3">{a.owner}</td>
                    <td className="px-2 py-3">
                      <span className={`rounded-full px-2 py-0.5 text-xs font-medium ${PRIORITY_STYLE[a.priority]}`}>
                        {a.priority}
                      </span>
                    </td>
                    <td className="whitespace-nowrap px-2 py-3">{a.dueDate}</td>
                    <td className="px-2 py-3 text-slate-600">{a.metric}</td>
                    <td className="px-4 py-3">
                      <select
                        value={current}
                        onChange={(e) =>
                          setStatus((s) => ({ ...s, [a.title]: e.target.value as ActionStatus }))
                        }
                        className="rounded-md border border-slate-300 bg-white px-2 py-1 text-xs"
                      >
                        {STATUSES.map((st) => (
                          <option key={st}>{st}</option>
                        ))}
                      </select>
                    </td>
                  </tr>
                );
              })}
            </tbody>
          </table>
        </div>
      )}
    </section>
  );
}